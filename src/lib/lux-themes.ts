/** جلب قالب بالمعرّف مع ارجوع للقالب الافتراضي عند عدم التوفر */
export function getLuxTheme(id: string | null | undefined): LuxTheme {
  return LUX_THEMES.find((t) => t.id === id) || LUX_THEMES[0];
}

/** كل معرفات القوالب الصالحة (للتحقق في الـ API) */
export const LUX_THEME_IDS = LUX_THEMES.map((t) => t.id);

/** اقتراح قالب مناسب لمنتج حسب اسمه ووصفه (يُستخدم في العرض الحي بالصفحة الرئيسية) */
export function suggestThemeForProduct(name: string, description: string): LuxTheme {
  const text = `${name} ${description}`.toLowerCase();

  const rules: { keywords: string[]; id: string }[] = [
    { keywords: ["عطر", "perfume", "parfum", "مسك", "عود"], id: "royal-onyx" },
    { keywords: ["عسل", "honey", "تمر", "دقلة", "زيت زيتون"], id: "golden-honey" },
    { keywords: ["ساعة", "watch", "مجوهرات", "ذهب", "خاتم", "سلسلة"], id: "royal-onyx" },
    { keywords: ["هاتف", "iphone", "سامسونج", "samsung", "حاسوب", "pc", "بلايستيشن", "gamer", "قيمينغ"], id: "cyber-titanium" },
    { keywords: ["شكولات", "شوكولا", "chocolat", "حلويات"], id: "dark-chocolate" },
    { keywords: ["بقلاوة", "فستق", "كعك", "باتي"], id: "imperial-pistachio" },
    { keywords: ["قفطان", "كاركوسوب", "قركوسوب", "عباية", "فستان", "زفاف", "ربطة"], id: "emerald-gold" },
    { keywords: ["جلد", "حذاء", "sac", "حقيبة", "محفظة"], id: "amber-mahogany" },
    { keywords: ["زليج", "فخار", "سجادة", "زرابي", "ديكور", "نحاس"], id: "artisan-zellige" },
    { keywords: ["أثاث", "مطبخ", "كنبة", "طاولة", "ديكور منزلي"], id: "nordic-minimalist" },
    { keywords: ["أطفال", "بيبي", "مواليد", "poussette", "طفل"], id: "royal-baby-blue" },
    { keywords: ["سيارة", "auto", "moto", "خوذة", "قطع غيار"], id: "black-carbon" },
  ];

  for (const rule of rules) {
    if (rule.keywords.some((k) => text.includes(k))) {
      const theme = LUX_THEMES.find((t) => t.id === rule.id);
      if (theme) return theme;
    }
  }

  // افتراضي: التناوب حسب أول حرف للاسم لإحساس بالتنوع
  const pool = ["royal-onyx", "emerald-gold", "oud-amber", "golden-honey"];
  const idx = (name.charCodeAt(0) || 0) % pool.length;
  return getLuxTheme(pool[idx]);
}
