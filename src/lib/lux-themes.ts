/** خصائص التنسيق الكاملة التي تُطبَّق على واجهة المتجر العامة */
export interface LuxThemeStyles {
  /** خلفية ترويسة المتجر (تدرج CSS كامل) */
  heroBg: string;
  heroText: string;
  heroMuted: string;
  badgeBg: string;
  badgeBorder: string;
  badgeText: string;
  /** خلفية صفحة المتجر */
  bodyBg: string;
  /** خلفية بطاقة المنتج */
  cardBg: string;
  cardText: string;
  priceColor: string;
  /** لون التمييز الأساسي (أيقونات، حلقات، لمسات) */
  accent: string;
  /** خلفية ناعمة للتمييز (شرائط الثقة، تركيز البحث) */
  accentSoft: string;
  buttonBg: string;
  buttonText: string;
  border: string;
  footerBg: string;
  footerText: string;
  /** فئة خط العناوين: font-display | font-amiri | font-cairo */
  fontClass: string;
  pattern: "dots" | "grid" | "none";
  /** كرات زخرفية متوهجة خلف الترويسة */
  glow1: string;
  glow2: string;
}

export interface LuxTheme {
  id: string;
  slug: string;
  nameAr: string;
  nameFr: string;
  category: LuxCategory;
  icon: string;
  /** لأي نوع من المنتجات يُنصح بهذا القالب */
  idealFor: string;
  mode: "dark" | "light";
  styles: LuxThemeStyles;
}

